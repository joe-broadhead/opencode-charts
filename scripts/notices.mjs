// The root NOTICE: the top block and the design section are hand-written and stay exactly as they are; the per-package
// blocks between them are generated from the licence texts, sorted by name and version. A missing design heading means
// the file is not the NOTICE this repository ships, so the build stops rather than writing over it.
export function notice(existing, root, packages) {
  const designAt = existing.indexOf(NOTICE_DESIGN_HEADING)
  if (designAt < 0) throw new Error(`build: NOTICE has no "${NOTICE_DESIGN_HEADING}" section.`)
  const before = existing.slice(0, designAt)
  const firstHeading = before.search(/^## /m)
  const top = firstHeading < 0 ? before : before.slice(0, firstHeading)
  if (!top.startsWith("charts-plugin\n") || !top.includes("\n\nThe published package bundles")) throw new Error("build: NOTICE's top block is not the expected plugin copyright and third-party summary.")
  const design = existing.slice(designAt)
  const blocks = packages.map(pkg => {
    const licence = licenceFor(root, pkg)
    const text = licence.text.trimEnd()
    return `## ${pkg.name} ${pkg.version} (${pkg.license})\n\n${text}${licence.note ? `\n\n${licence.note}` : ""}\n`
  })
  return `${top}${blocks.join("\n")}\n${design}`
}
